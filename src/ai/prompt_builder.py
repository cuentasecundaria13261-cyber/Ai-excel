import json
import math
 
import pandas as pd
 
 
def convert_to_json_safe(value):
    """Convert Pandas and Python objects into JSON-safe values."""
 
    if isinstance(value, pd.Series):
        return {
            str(key): convert_to_json_safe(item)
            for key, item in value.items()
        }
 
    if isinstance(value, pd.DataFrame):
        return convert_to_json_safe(value.to_dict(orient="records"))
 
    if isinstance(value, dict):
        return {
            str(key): convert_to_json_safe(item)
            for key, item in value.items()
        }
 
    if isinstance(value, (list, tuple)):
        return [convert_to_json_safe(item) for item in value]
 
    if value is pd.NA:
        return None
 
    if isinstance(value, (pd.Timestamp, pd.Period)):
        return str(value)
 
    if hasattr(value, "item"):
        return convert_to_json_safe(value.item())
 
    if isinstance(value, float) and (math.isnan(value) or math.isinf(value)):
        return None
 
    return value
 
 
def build_fact_catalog(analytics):
    """
    Flatten calculated analytics into individually identifiable facts.
 
    These facts are generated by Python, not by the AI model.
    Floats are rounded to 2 decimals so the AI copies clean numbers.
    """
 
    safe_analytics = convert_to_json_safe(analytics)
    facts = []
 
    def add_facts(value, path):
        if isinstance(value, dict):
            for key, child in value.items():
                child_path = f"{path}.{key}" if path else str(key)
                add_facts(child, child_path)
 
        elif isinstance(value, list):
            for index, child in enumerate(value):
                add_facts(child, f"{path}[{index}]")
 
        else:
            if isinstance(value, float):
                value = round(value, 2)
 
            facts.append({
                "id": f"F{len(facts) + 1:03d}",
                "path": path,
                "value": value,
            })
 
    add_facts(safe_analytics, "analytics")
 
    return facts
 
 
def convert_percentage(value):
    """Convert a numeric value to a qualitative percentage description."""
    if value is None:
        return None
    if isinstance(value, float) and math.isnan(value):
        return None
 
    if value == 0:
        return "negligible"
    elif value < 0.1:
        return "a very small portion"
    elif value < 0.25:
        return "a small portion"
    elif value < 0.5:
        return "a moderate portion"
    elif value < 0.75:
        return "a large portion"
    elif value < 0.9:
        return "a very large portion"
    else:
        return "nearly all"
 
 
